    used_b = set(excluded_b)
    generators = {seed: Generator(seed) for seed in seeds}
    expected = {}
    expected_pre = {}
    expected_final = {}
    for seed in seeds:
        expected[seed] = {split: generate(generators[seed], used_b, split, config["counts"][split])
                          for split in ("training", "development")}
        expected_pre[seed] = {"state": generators[seed].state, "global_reserved_b": sorted(used_b)}
    for seed in seeds:
        expected[seed]["assessment"] = generate(generators[seed], used_b, "assessment", config["counts"]["assessment"])
