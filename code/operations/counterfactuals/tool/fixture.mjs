// Independently authored engineering example. These are recorded synthetic
// values, not execution evidence for an encoder, fitted readout or application.
import {createHash} from 'node:crypto';

export function makeExampleRequest({providerId = 'example-provider-A', dimensions = 4} = {}) {
  if (typeof providerId !== 'string' || !/^[A-Za-z0-9._-]{1,128}$/.test(providerId))
    throw new Error('Example providerId must be 1–128 ASCII letters, digits, dots, underscores or hyphens');
  if (!Number.isSafeInteger(dimensions) || dimensions < 1 || dimensions > 1024)
    throw new Error('Example dimensions must be an integer from 1 to 1024');
  const prefix = `${providerId}-d${dimensions}`;
  const artifacts = [];
  const makeArtifact = (name, value) => {
    const id = `${prefix}:${name}`;
    const bytes = Buffer.from(`${JSON.stringify(value, null, 2)}\n`, 'utf8');
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    artifacts.push({id, sha256, bytes});
    return {id, sha256};
  };
  const engineering = 'Artificial recorded-response engineering demonstration; no scientific or provider-quality evidence';
  const provider = makeArtifact('provider', {provider_id: providerId, revision: 'recorded-fixture-v1',
    dimensions, scope: engineering, execution: 'No encoder or external service is executed'});
  const preprocessing = makeArtifact('preprocessing', {identity: 'fixture-identity-preprocessing-v1', fitted: false});
  const fittedTransform = makeArtifact('fitted-transform', {identity: 'fixture-identity-transform-v1', fitted: false});
  const responseModel = makeArtifact('response-model', {identity: 'fixture-recorded-response-v1', fitted: false,
    scope: engineering, execution: 'Numerical responses are explicitly pre-recorded, not generated by a model call'});
  const constructor = makeArtifact('constructor', {identity: 'fixture-input-setting-edit-v1',
    changed: {setting: [1, 3]}, held_fixed: {load: 2}});
  const supportPolicy = makeArtifact('support-policy', {identity: 'fixture-support-v1',
    rule: 'Both scalar attributes must lie in [0,10]; load must be held fixed', scope: engineering});
  const sourceCode = makeArtifact('source-description', {identity: 'fixture-source-description-v1',
    scope: engineering, note: 'A descriptor of artificial supplied records; not an authenticated implementation identity'});
  const configuration = makeArtifact('configuration', {identity: 'fixture-configuration-v1',
    provider_id: providerId, dimensions, stochastic_policy: 'deterministic', tolerance: 0});
  const permissions = makeArtifact('permissions', {identity: 'fixture-use-v1', scope: engineering,
    permitted: 'Write and compare this project-authored artificial fixture; no training, APIs, data acquisition or GPU work'});
  const spaceArtifact = makeArtifact('space', {provider, preprocessing, fitted_transform: fittedTransform,
    native_shape: [dimensions], normalization: 'none', geometry: 'euclidean', input_role: 'response_input'});
  const expectedSpace = {artifact: spaceArtifact, provider, preprocessing, fitted_transform: fittedTransform,
    output_selector: 'fixture-recorded-vector', native_shape: [dimensions], layout: 'dense',
    normalization: 'none', geometry: 'euclidean', input_role: 'response_input'};
  const dependencies = [
    ['provider', provider], ['preprocessing', preprocessing], ['fitted_transform', fittedTransform],
    ['response_model', responseModel], ['support_policy', supportPolicy], ['constructor', constructor],
    ['operation_source', sourceCode], ['operation_configuration', configuration], ['permissions_record', permissions],
  ].map(([role, artifact]) => ({role, artifact, fit_population: 'not_fitted',
    selection_population: 'not_fitted', pretraining_exposure: 'excluded_by_design', available_at: null}));
  const pipelineArtifact = makeArtifact('pipeline', {identity: 'fixture-recorded-pipeline-v1',
    space: spaceArtifact, response_model: responseModel, configuration, dependencies, scope: engineering});
  const expectedPipeline = {artifact: pipelineArtifact, response_model: responseModel,
    configuration_sha256: configuration.sha256, stochastic_policy: 'deterministic',
    provider_revision_known: true, dependencies};
  const axes = [
    {id: 'response-one', definition_revision: 'fixture-response-one-v1', units: 'synthetic_unit'},
    {id: 'response-two', definition_revision: 'fixture-response-two-v1', units: 'synthetic_unit'},
  ];
  const sourceObservation = makeArtifact('source-observation', {setting: 1, load: 2, scope: engineering});
  const baselineInput = makeArtifact('baseline-input', {setting: 1, load: 2});
  const alternativeInput = makeArtifact('alternative-input', {setting: 3, load: 2,
    parent_input_id: baselineInput.id, constructor});
  const baselineRepresentation = makeArtifact('baseline-representation', {space_id: spaceArtifact.id,
    values: Array.from({length: dimensions}, (_, index) => index + 1), scope: engineering});
  const alternativeRepresentation = makeArtifact('alternative-representation', {space_id: spaceArtifact.id,
    values: Array.from({length: dimensions}, (_, index) => index === 0 ? 3 : index + 1), scope: engineering});
  const baselineResponse = makeArtifact('baseline-response', {axes, values: [2, -1]});
  const alternativeResponse = makeArtifact('alternative-response', {axes, values: [5, -3]});
  const baselineMask = makeArtifact('baseline-mask', {selected_output_position: 0, valid: true});
  const alternativeMask = makeArtifact('alternative-mask', {selected_output_position: 0, valid: true});
  const timing = {support_start: null, support_end: null, available_at: null, vintage: 'fixture-recorded-v1'};
  const baseline = {input: baselineInput, source_observation: sourceObservation, parent_input_id: '',
    origin: 'observed', representation: baselineRepresentation, representation_kind: 'observation_embedding',
    parent_representation_id: '', space: expectedSpace, pipeline: pipelineArtifact, response: baselineResponse,
    response_execution_id: `${prefix}:baseline-recorded-response`, output_position: 0, mask: baselineMask,
    output_valid: true, upstream_succeeded: true, timing,
    attributes: [{name: 'setting', units: 'unit', value: 1}, {name: 'load', units: 'unit', value: 2}],
    axes, response_values: [2, -1]};
  const alternative = {input: alternativeInput, source_observation: sourceObservation,
    parent_input_id: baselineInput.id, origin: 'edited_input', representation: alternativeRepresentation,
    representation_kind: 'transformed_candidate', parent_representation_id: baselineRepresentation.id,
    space: expectedSpace, pipeline: pipelineArtifact, response: alternativeResponse,
    response_execution_id: `${prefix}:alternative-recorded-response`, output_position: 0, mask: alternativeMask,
    output_valid: true, upstream_succeeded: true, timing,
    attributes: [{name: 'setting', units: 'unit', value: 3}, {name: 'load', units: 'unit', value: 2}],
    axes, response_values: [5, -3]};
  const controlEvidence = makeArtifact('control-evidence', {changed: 'setting: 1 to 3', held_fixed: 'load: 2',
    scope: engineering, verification: 'Supplied artificial fixture assertion; no source semantics are independently proved'});
  const passed = name => ({state: 'passed', evidence: makeArtifact(`${name}-evidence`,
    {check: name, state: 'passed', scope: engineering}), detail: `Artificial fixture ${name} assertion`});
  const pairs = [{id: `${prefix}:pair-1`, unit_id: `${prefix}:unit-1`, entity_id: `${prefix}:entity-1`,
    group_id: `${prefix}:group-1`, baseline, alternative, constructor,
    change_definition: 'Change setting from 1 to 3; hold load fixed at 2',
    interpretation: 'model_input_response', control_evidence: controlEvidence,
    alternative_validity: passed('validity'), support: passed('support'), interpretability: passed('interpretability')}];
  const input = {request_id: `${prefix}:request-1`, operation_run_id: `${prefix}:run-1`,
    contract_id: 'OR06-PCR', contract_revision: '0.1.0', rer_id: 'OR06-PCR-RER', rer_revision: '0.1.0',
    claim_level: 'controlled_model_response', purpose: engineering, population_id: `${prefix}:fixture-population`,
    sampling_rule: 'The one explicitly supplied artificial pair; no population estimate', response_horizon: 'static-recorded-response',
    permitted_interpretation: 'model_input_response', permissions_ref: permissions.id,
    resource_budget: 'One recorded pair; CPU arithmetic only; no model execution or fitting',
    evidence_destination: 'caller-selected-new-tool-output-directory', code_sha256: sourceCode.sha256,
    configuration_sha256: configuration.sha256, temporal_mode: 'non_temporal', as_of: null,
    non_temporal_justification: 'Artificial static records have no event chronology or real-world information horizon',
    expected_space: expectedSpace, expected_pipeline: expectedPipeline, response_axes: axes, selected_output_position: 0,
    attribute_rules: [{name: 'setting', units: 'unit', role: 'changed', minimum: 0, maximum: 10},
      {name: 'load', units: 'unit', role: 'held_fixed', minimum: 0, maximum: 10}],
    control_tolerance: 0, pairs};
  return {input, artifacts};
}
